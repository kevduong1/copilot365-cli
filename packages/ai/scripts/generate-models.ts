#!/usr/bin/env node
import { writeFile } from "node:fs/promises";

// Static local-only declarations. Generation never contacts an external catalog.
const source = `// Generated by scripts/generate-models.ts. Do not edit.
import { localModel } from "./providers/local.ts";

const model = localModel();
export const MODELS = { local: { [model.id]: model } };
export const IMAGE_MODELS = { local: {} };
export const CLASSIFIER_MODELS = { local: {} };
`;
await writeFile(new URL("../src/models.generated.ts", import.meta.url), source);
